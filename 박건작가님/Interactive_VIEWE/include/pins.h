#pragma once
/*
 * ======================================================================================
 * [핀 매핑] VIEWE UEDX80480043E-WB-A / WB-B  (ESP32-S3-WROOM-1 N16R8)
 * ======================================================================================
 * 근거: VIEWE 공식 SPEC (WB-A V3.2, WB-B V1.0) + 회로도 (WB-A V1.3, WB-B)
 *
 *  - 온보드 4.3" RGB 화면이 GPIO 1~9, 14~16, 21, 39~42, 45~48, 2(백라이트)를 상시 사용.
 *  - 이 작품은 터치를 쓰지 않으므로 터치용 GPIO38(RST), GPIO19/20(I2C)을 재활용.
 *    · HX711 SCK(평소 LOW)가 GPIO38에 물려 GT911 터치칩은 리셋 상태로 꺼져 있음.
 *  - SD카드(온보드 슬롯)를 쓰므로 GPIO10/13은 SD 전용. SPI 버스(11/12/13)를
 *    SD + 2.8" ST7789 + MAX7219 세 장치가 공유하고 CS만 따로 둔다.
 *  - Serial(GPIO43/44, CH340)은 그대로 살려 둠 → 업로드·시리얼 모니터 정상.
 * ======================================================================================
 */

// ---- 공유 SPI 버스 (SPI2 / FSPI) ----------------------------------------------------
constexpr int PIN_SPI_SCLK = 12;   // J2-12 : SD SCLK  + ST7789 SCL + MAX7219 CLK
constexpr int PIN_SPI_MOSI = 11;   // J2-11 : SD MOSI  + ST7789 SDA + MAX7219 DIN
constexpr int PIN_SPI_MISO = 13;   // J2-13 : SD MISO 전용 (외부 배선 없음)

// ---- 온보드 MicroSD -----------------------------------------------------------------
constexpr int PIN_SD_CS    = 10;   // J2-10 : 온보드 배선, 외부 연결 없음

// ---- 2.8" ST7789 정보 LCD (240x320) -------------------------------------------------
constexpr int PIN_INFO_CS  = 19;   // J2-17
constexpr int PIN_INFO_DC  = 20;   // J2-16
constexpr int PIN_INFO_RST = -1;   // 모듈 RST → 3.3V 고정 (소프트웨어 리셋 사용)

// ---- MAX7219 8자리 7세그먼트 --------------------------------------------------------
constexpr int PIN_SEG_CS   = 0;    // J3-16 (BOOT 버튼 핀. 부팅 시 HIGH 유지되어 문제 없음)

// ---- HX711 로드셀 앰프 ---------------------------------------------------------------
constexpr int PIN_HX_DT    = 17;   // J2-9
constexpr int PIN_HX_SCK   = 38;   // J2-15 (터치 RST 겸용 → 터치 비활성)

// ---- 선택: 패시브 부저 ---------------------------------------------------------------
// 남는 핀이 없어 기본 비활성(-1).
//  · J2-14(실크 '18')가 GPIO18과 통전되면(R33 장착) 18로 설정
//  · 또는 Serial을 포기하고 43(TX)로 설정
constexpr int PIN_BUZZER   = -1;

// ---- 온보드 고정 핀 (참고용, 변경 금지) ---------------------------------------------
constexpr int PIN_MAIN_BL  = 2;    // 4.3" 백라이트
